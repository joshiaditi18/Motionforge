"""
error_codes.py — MOTIONFORGE Phase 5 Official Validation Error Codes

Defines stable error codes returned by the submission validator.
These codes provide deterministic categorization of validation rejections
and errors without exposing internal system paths or confidential data.
"""

from enum import Enum


class ErrorCode(str, Enum):
    # --- Archive Errors ---
    ARCHIVE_NOT_FOUND = "ARCHIVE_NOT_FOUND"
    ARCHIVE_CORRUPTED = "ARCHIVE_CORRUPTED"
    ARCHIVE_TOO_LARGE = "ARCHIVE_TOO_LARGE"
    ARCHIVE_TOO_MANY_FILES = "ARCHIVE_TOO_MANY_FILES"
    SUSPICIOUS_COMPRESSION_RATIO = "SUSPICIOUS_COMPRESSION_RATIO"

    # --- Security & Path Traversal Errors ---
    PATH_TRAVERSAL = "PATH_TRAVERSAL"
    UNSAFE_SYMLINK = "UNSAFE_SYMLINK"
    FORBIDDEN_FILE_TYPE = "FORBIDDEN_FILE_TYPE"

    # --- Schema & File Layout Errors ---
    INVALID_METADATA = "INVALID_METADATA"
    MISSING_REQUIRED_DIRECTORY = "MISSING_REQUIRED_DIRECTORY"
    MISSING_REQUIRED_FILE = "MISSING_REQUIRED_FILE"
    UNEXPECTED_FILE = "UNEXPECTED_FILE"
    INVALID_TASK = "INVALID_TASK"

    # --- BVH Syntax & Formatting Errors ---
    INVALID_BVH = "INVALID_BVH"
    INVALID_BVH_HEADER = "INVALID_BVH_HEADER"
    INVALID_FPS = "INVALID_FPS"
    INVALID_FRAME_TIME = "INVALID_FRAME_TIME"
    INVALID_FRAME_COUNT = "INVALID_FRAME_COUNT"

    # --- Skeleton & Topology Errors ---
    INVALID_HIERARCHY = "INVALID_HIERARCHY"
    INVALID_ROOT_JOINT = "INVALID_ROOT_JOINT"
    INVALID_JOINT_COUNT = "INVALID_JOINT_COUNT"
    INVALID_JOINT_NAMES = "INVALID_JOINT_NAMES"
    INVALID_JOINT_ORDER = "INVALID_JOINT_ORDER"
    INVALID_CHANNEL_COUNT = "INVALID_CHANNEL_COUNT"
    INVALID_CHANNEL_ORDER = "INVALID_CHANNEL_ORDER"
    INVALID_END_SITE = "INVALID_END_SITE"

    # --- Motion & Numerical Errors ---
    INVALID_MOTION_SHAPE = "INVALID_MOTION_SHAPE"
    NAN_DETECTED = "NAN_DETECTED"
    INF_DETECTED = "INF_DETECTED"
    EMPTY_MOTION_DATA = "EMPTY_MOTION_DATA"

    # --- Task-Specific Errors ---
    INVALID_TARGET = "INVALID_TARGET"
    OBSERVED_FRAME_MODIFIED = "OBSERVED_FRAME_MODIFIED"
    BONE_LENGTH_VIOLATION = "BONE_LENGTH_VIOLATION"

    # --- System & Internal Errors ---
    INTERNAL_VALIDATION_ERROR = "INTERNAL_VALIDATION_ERROR"
